def NEWS(n, outlet, date, head, summ, url):
    """A press item: outlet and date, the headline, a two sentence summary in our own words, and a link to the article."""
    inner = (f'<small>{TX(outlet)} · {TX(date)}</small><b>{TX(head)}</b><p>{TX(summ)}</p>'
             + (f'<a href="{url}" target="_blank" rel="noopener">לכתבה המלאה ↗</a>' if MODE == 'deck' else f'<span class="nurl" dir="ltr">{url}</span>'))
    return ST(n, inner, cls='news') if n else f'<div class="news">{inner}</div>'


def NEWSSLIDE(part, h, lead, items, take):
    S(f's-news{part}', f'מהעיתונות: חלק {part}', h,
      '<p class="lead">' + TX(lead) + '</p><div class="newsrow">' + ''.join(NEWS(i + 1, *it) for i, it in enumerate(items)) + '</div>'
      + ST(len(items) + 1, TX(take), cls='band dg'), kick=f'חלק {part} · בעולם האמיתי', cls='pfs')


def CALL(n, num, text):
    """A numbered callout beside a trading screen."""
    return ST(n, f'<b>{num}</b><span>{TX(text)}</span>', cls='callo')


def FLY(n, x, y, w, d, text):
    """A flying callout over a trading terminal. d: the side the arrow leaves the bubble from (u, d, l, r). Only the newest one is visible."""
    return f'<div class="st fly f-{d}" data-n="{n * 10}" style="left:{x}px;top:{y}px;width:{w}px"><b>{n}</b><span>{TX(text)}</span></div>'


def TERM(sid, title, h, lead, inner, flies, kick):
    """A trading terminal mock-up with flying explanations. In the PDF: the explanations as a numbered list."""
    if MODE == 'pdf':
        S(sid, title, h, f'<p>{TX(lead)}</p><ol>' + ''.join(f'<li>{TX(t)}</li>' for _, _, _, _, _, t in flies) + '</ol>', kick=kick)
        return
    S(sid, title, h, f'<p class="lead tl-lead">{TX(lead)}</p><div class="tterm" dir="ltr">{inner}' + ''.join(FLY(i + 1, *f[1:]) if True else '' for i, f in enumerate(flies)) + '</div>', kick=kick, cls='terms')


