# Recap of lesson 2, rebuilt as gradual flowcharts: the letters on a timeline first, then one flow per position, one idea per click.
def _nd(n, head, body, cls=''):
    return ST(n, f'<b class="nh">{TX(head)}</b><div class="nb">{body}</div>', cls='nd ' + cls)


def _ar(n):
    return ST(n, '<span>←</span>', cls='ar')


def PFLOW(sid, title, h, who_he, who_en, en_note, duty, ask, yes, no, payoff, why, pnl, story, scen, kick, tone, mirror=None):
    """One position as a flow: who am I, right or duty, the expiry question, the payoff, then a story with two prices."""
    c1 = (f'<div class="col">{ST(1, "<b class=\'nh\'>מי אני</b><div class=\'he\'>" + TX(who_he) + "</div>", cls="nd who")}'
          + ST(2, f'<div class="en" dir="ltr">{who_en}</div><div class="enx">{TX(en_note)}</div>', cls='nd en2') + '</div>')
    c2 = f'<div class="col">{_nd(3, "זכות או חובה?", TX(duty), "duty")}</div>'
    c3 = (f'<div class="col dec">{ST(4, "<b class=\'nh\'>ביום הפקיעה</b><div class=\'q\'>" + TX(ask) + "</div>", cls="nd ask")}'
          + f'<div class="br">{ST(5, "<b class=\'yn y\'>כן</b>" + TX(yes), cls="nd yes")}{ST(6, "<b class=\'yn n\'>לא</b>" + TX(no), cls="nd no")}</div></div>')
    c4 = (f'<div class="col">{ST(7, "<b class=\'nh\'>תזרים (Payoff)</b><div class=\'f\' dir=\'ltr\'>" + TX(payoff) + "</div><div class=\'why\'>" + TX(why) + "</div>", cls="nd pay")}'
          + ST(8, "<b class='nh'>רווח (P&L)</b><div class='f' dir='ltr'>" + TX(pnl[0]) + "</div><div class='why'>" + TX(pnl[1]) + "</div>", cls='nd pnl') + '</div>')
    flow = f'<div class="pf {tone}">{c1}{_ar(3)}{c2}{_ar(4)}{c3}{_ar(7)}{c4}</div>'
    sc = ''.join(ST(9 + i, f'<b class="sp2">{TX(t)}</b>' + ''.join(f'<div class="ln">{TX(x)}</div>' for x in lines), cls='scn ' + c) for i, (t, lines, c) in enumerate(scen))
    ex = f'<div class="pfx">{ST(9, "<b class=\'nh\'>דוגמה</b>" + TX(story), cls="story")}{sc}</div>'
    mir = ST(1, TX(mirror), cls='mir') if mirror else ''
    S(sid, title, h, mir + flow + ex, kick=kick, cls='pfs')


