def _H_CASE(sid, title, story, qtext, a, why, rem, rows, concl, meme):
    """A case: the story and the question on the right, a solution table that opens row by row on the left."""
    q = mc(sid + '-q', qtext, _OPT3, a, why, rot=False, rem=rem)
    n = len(rows) + 1
    sol = (TABLES(['מה בודקים', 'ערך', 'איך ולמה'], rows, 'h-ct')
           + ST(n, f'<b>מסקנה:</b> {TX(concl)}', cls='band ans') + MEME(*meme, n + 1))
    S(sid, title, title, f'<div class="qg"><div class="qr"><div class="card qstem"><p>{TX(story)}</p></div>{q}{_H_LEGEND}</div><div class="solw card">{sol}</div></div>',
      kick=f'חלק {CUR[0]} · מקרה', cls='qslide')


