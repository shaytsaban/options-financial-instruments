def _H_MORE(label, rows):
    """Terms of one exercise, behind a red line: term, plain meaning, small numeric demo."""
    # raw text: the task that holds it passes through TX once
    t = ''.join(f'<tr><td><b>{a}</b></td><td>{b}</td><td>{c}</td></tr>' for a, b, c in rows)
    return MORE('📖 ' + label, f'<table class="tbl2 h-mt"><tr><th>מושג</th><th>בפשטות</th><th>דוגמה מספרית</th></tr>{t}</table>')


def _H_SYM(text):
    """The letters of an exercise, under its formulas. An English name in parentheses never breaks across lines."""
    text = re.sub(r'\(([A-Za-z][A-Za-z ]+)\)', r'<span class="h-nw">(\1)</span>', text)
    return f'<div class="h-sym">{text}</div>'


def _H_WT(rows):
    """A worked explanation as a labelled table: what, value, how and why."""
    t = ''.join(f'<tr><td>{TX(a)}</td><td class="v">{TX(b)}</td><td>{TX(c)}</td></tr>' for a, b, c in rows)
    return f'<table class="tbl2 h-wt"><tr><th>מה</th><th>ערך</th><th>איך ולמה</th></tr>{t}</table>'


def _H_mc(qid, q, opts, a, why, rem, rot=True):
    """A multiple choice question laid out as one row: the story, the options, then the formula and the explanation."""
    r = sum(map(ord, qid)) % len(opts) if rot else 0
    opts = opts[r:] + opts[:r]
    a = (a - r) % len(opts)
    o = ''.join(f'<button class="o{" correct" if MODE == "pdf" and i == a else ""}" data-i="{i}">{"אבגדה"[i]}. {TX(t)}</button>' for i, t in enumerate(opts))
    return (f'<div class="mc" data-a="{a}" id="{qid}"><div class="h-mq"><div class="q">{TX(q)}</div><div class="rem"><b>📐 נוסחה:</b> {TX(rem)}</div></div>'
            f'<div class="h-mo">{o}</div><div class="h-mw"><div class="w">{why}</div></div></div>')


def _H_SOLVE(sid, title, h, story, parts, hints, remind, box, side, head, rows, pdf_steps):
    """SOLVE with the same buttons, laid out on the whole slide. The solution is a table whose rows open one per click."""
    if MODE == 'pdf':
        SOLVE(sid, title, h, story, parts, hints, remind, pdf_steps)
        return
    NACT[0] += 1
    ps = ''.join(f'<label class="svp" data-a="{a}" data-tol="{t}"><span>{TX(l)}</span><input dir="ltr" inputmode="decimal" autocomplete="off" spellcheck="false"></label>' for l, a, t in parts)
    btn = lambda c, t: f'<button class="abtn ghost {c}">{t}</button>'
    th = ''.join(f'<th>{TX(x)}</th>' for x in head)
    trs = ''.join('<tr class="svs">' + ''.join(f'<td>{TX(c)}</td>' for c in r) + '</tr>' for r in rows)
    cfgd = dict(hints=[TX(x) for x in hints], remind=TX(remind))
    S(sid, title, h,
      f'<div class="act sv" id="{sid}-w" data-cfg="{_cfg(cfgd)}"><div class="tasktxt">{TX(story)}</div>'
      f'<div class="h-svg"><div class="h-svr"><div class="sv-fm"><b>📐 הנוסחאות לתרגיל, במילים ובאותיות</b><div>{TX(box)}</div></div>{side}</div>'
      f'<div class="h-svl"><div class="svps">{ps}</div><div class="actbar">{CHK}{btn("hnt", "💡 רמז")}{btn("rmd", "📐 תזכורת נוסחה")}{btn("prt", "פתרון חלקי")}{btn("ful", "פתרון מלא")}{RST}</div>'
      f'<div class="fbbar">תשובות בשקלים. ״פתרון מלא״ ממלא שורה בטבלה שלמטה.</div></div></div>'
      f'<table class="tbl2 h-sol"><tr>{th}</tr>{trs}</table></div>', kick=f'חלק {CUR[0]} · תרגיל')


