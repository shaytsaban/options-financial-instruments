# ================================================================ helpers of this section (prefix _G_), used here and in content_e1.py
def _G_FM(html, title='📐 הנוסחאות לשאלה'):
    """A formula box that stays visible beside a question: the formula in words and in letters."""
    return f'<div class="g-fm"><b>{title}</b><div>{TX(html)}</div></div>'


def _G_WT(rows, start=1, head=('מה מחשבים, ולמה', 'הנוסחה', 'הצבה ותוצאה')):
    """A worked solution as a labelled table. Each row: what we compute (and why), the formula, then the substitution and the result.
    rows: (name, why, formula, substitution, result). Every cell is one click."""
    n, b = start, ''
    for name, why, f, sub, val in rows:
        c1 = ST(n, f'<b class="gv">{TX(name)}</b>' + (f'<span class="gm">{TX(why)}</span>' if why else ''))
        c2 = ST(n + 1, f'<span class="g-f">{TX(f)}</span>')
        c3 = ST(n + 2, f'<span class="g-sub">{TX(sub)}</span><b class="gv">{TX(val)}</b>')
        b += f'<tr><td>{c1}</td><td>{c2}</td><td>{c3}</td></tr>'
        n += 3
    h = ''.join(f'<th>{TX(x)}</th>' for x in head)
    return f'<table class="tbl2 g-wt"><tr>{h}</tr>{b}</table>', n


def _G_Q(sid, tag, title, stem, fm, rows, ans, note=None, side=''):
    """A worked question: the story and its formulas on one side, the labelled solution table on the other."""
    head = f'{tag}: {title}'
    t, n = _G_WT(rows)
    end = ST(n, f'<b>תשובה:</b> {TX(ans)}', cls='band ans') + ''.join(BAND(a, x, n + 1 + i) for i, (a, x) in enumerate(note or []))
    stem_html = ''.join(f'<p>{TX(x)}</p>' for x in stem)
    S(sid, head, head, f'<div class="qg"><div class="qr"><div class="card qstem">{stem_html}</div>{_G_FM(fm)}{side}</div><div class="solw">{t}{end}</div></div>',
      kick=f'חלק {CUR[0]} · {tag}', cls='qslide')


def _G_RT(head, rows, start=1, keep=1, cls=''):
    """A table whose first `keep` columns are visible. The rest of each row appears together, one click per row."""
    h = ''.join(f'<th>{TX(x)}</th>' for x in head)
    b = ''.join('<tr>' + ''.join(f'<td>{TX(c)}</td>' if j < keep else f'<td>{ST(start + i, TX(c))}</td>' for j, c in enumerate(r)) + '</tr>' for i, r in enumerate(rows))
    return f'<table class="tbl2 {cls}"><tr>{h}</tr>{b}</table>'


def _G_CASE(sid, title, story, qtext, opts, a, why, steps, rem='', side=''):
    """One situation on its own slide, with the formulas beside the question. steps: ready HTML, revealed by clicks."""
    q = mc(sid + '-q', qtext, opts, a, why, rot=False, rem=rem)
    S(sid, title, title, f'<div class="qg"><div class="qr"><div class="card qstem"><p>{TX(story)}</p></div>{q}{side}</div><div class="solw card">{steps}</div></div>',
      kick=f'חלק {CUR[0]} · מקרה', cls='qslide')


