def sheet(name, title, task, cells, widths, chart=None, learn=None):
    """cells: (addr, value, kind, fmt[, 'drag']). kind: h header, l label, g given, a answer (formula).
    task: one line (old books) or a list of lines: the story, then 'נדרש:' and the items.
    learn: (what we learned, the key formula in words), written in the solutions workbook only."""
    (PARKED if CURB[0] == 'parked' else BOOKS[CURB[0]]).append(dict(name=name, title=title, task=task, cells=cells, widths=widths, chart=chart, learn=learn))


def rows(col_start, row0, vals):
    return [(f'{col_start}{row0 + i}', v) for i, v in enumerate(vals)]


def top(task):   # first free row under a story: title, story lines, note, one empty row
    return len(task) + 4


def kv(r, pairs, kind='g'):   # label in A, value or formula in B, one pair per row
    out = []
    for i, p in enumerate(pairs):
        out += [(f'A{r + i}', p[0], 'l'), (f'B{r + i}', p[1], kind, p[2] if len(p) > 2 else None)]
    return out


def hdr(r, names):
    return [(f'{"ABCDEFGH"[i]}{r}', n, 'h') for i, n in enumerate(names)]


def giv(col, r0, vals, fmt=None):
    return [(f'{col}{r0 + i}', v, 'g', fmt) for i, v in enumerate(vals)]


def drag(col, r0, r1, f0, fmt=None):   # one formula, written for the first row and dragged down
    return [(f'{col}{r}', Translator(f0, origin=f'{col}{r0}').translate_formula(f'{col}{r}'), 'a', fmt, 'drag') for r in range(r0, r1 + 1)]


def chk(name, addr, expected):   # key answer, computed by hand from the numbers of the story
    CHK[CURB[0]][(name, addr)] = expected


