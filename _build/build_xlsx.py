def texts(L, SHEETS):
    for solved in (False, True):
        yield from first_lines(solved, L, SHEETS)
    for s in SHEETS:
        yield s['name']; yield s['title']; yield from s['task']; yield from (s['learn'] or ())
        for cell in s['cells']:
            if isinstance(cell[1], str): yield cell[1]


def lint(L, SHEETS):
    """Rules of the new books: full story with a 'נדרש:' list, no dashes or ellipsis, minimal anchoring, a 'what we learned' line."""
    bad = []
    for x in texts(L, SHEETS):
        if re.search('[—–‒―־…]|\\.\\.\\.', x): bad.append(('dash or ellipsis', x[:40]))
    for s in SHEETS:
        if not (isinstance(s['task'], list) and 'נדרש:' in s['task'] and s['task'].index('נדרש:') >= 1 and len(s['task']) - s['task'].index('נדרש:') >= 3): bad.append((s['name'], 'not a full story question'))
        if not s['learn']: bad.append((s['name'], 'no learn line'))
        for cell in s['cells']:
            if cell[2] != 'a': continue
            f = cell[1]; dragged = len(cell) > 4 and cell[4] == 'drag'
            if dragged and re.search(r'\$[A-Z]', f): bad.append((s['name'], cell[0], 'column locked in a formula that is dragged down', f))
            if not dragged and '$' in f: bad.append((s['name'], cell[0], 'anchor in a formula that is not dragged', f))
    return bad


def content(path):   # what a reader sees and what Excel computes: used to leave an unchanged file untouched
    wb = load_workbook(path); out = []
    for ws in wb:
        out.append((ws.title, ws.sheet_view.rightToLeft, len(ws._charts), sorted((k, v.width) for k, v in ws.column_dimensions.items())))
        for row in ws.iter_rows():
            for c in row:
                if c.value is not None or c.fill.fgColor.rgb not in (None, '00000000'):
                    out.append((ws.title, c.coordinate, c.value, c.number_format, c.fill.fgColor.rgb, c.font.b, c.font.sz, c.alignment.horizontal, c.alignment.readingOrder))
    return out


def ship(new, dst):
    if os.path.exists(dst) and content(new) == content(dst): return 'unchanged, kept'
    shutil.copy(new, dst); return 'written'


